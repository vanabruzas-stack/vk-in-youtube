let out = '// Generated by scripts/icons.mjs from @vkontakte/icons (MIT).\nexport const vkIcons = {\n';
for (const [name, file] of Object.entries(icons)) {
  const svg = (await readFile(resolve(root, `${file}.svg`), 'utf8'))
    .trim()
    .replace(/<svg /, '<svg aria-hidden="true" focusable="false" ');
  out += `  ${name}: ${JSON.stringify(svg)},\n`;
}
out += '} as const;\nexport type VkIconName = keyof typeof vkIcons;\n';
await writeFile(resolve('src/vk-design-system/vk-icons.generated.ts'), out);
